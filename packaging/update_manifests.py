#!/usr/bin/env python3
"""Writes the Scoop manifest (bucket/portal.json), the Homebrew formula
(Formula/portal.rb) and the winget manifests (packaging/winget/) for a release.

    python3 packaging/update_manifests.py v0.3.0 <folder with the release's *.sha256 files>

The release workflow runs this after publishing and commits the result, so
this repository doubles as a Scoop bucket and a Homebrew tap:

    scoop bucket add portal https://github.com/MStefa003/portal
    brew tap mstefa003/portal https://github.com/MStefa003/portal

The winget manifests are submitted to microsoft/winget-pkgs (see
docs/RELEASING.md).
"""

import json
import pathlib
import sys

REPO = "MStefa003/portal"
DESCRIPTION = "Send files and folders directly between two machines: peer-to-peer, end-to-end encrypted and resumable."
WINGET_ID = "MStefa003.Portal"
# Homebrew wants a short description without a final period.
BREW_DESC = "Peer-to-peer, end-to-end encrypted file and folder transfer"
ROOT = pathlib.Path(__file__).resolve().parent.parent


def sha256(folder: pathlib.Path, archive: str) -> str:
    text = (folder / f"{archive}.sha256").read_text(encoding="ascii")
    return text.split()[0].lower()


def main() -> None:
    tag, folder = sys.argv[1], pathlib.Path(sys.argv[2])
    version = tag.removeprefix("v")
    base = f"https://github.com/{REPO}/releases/download/{tag}"

    def archive(target: str) -> str:
        ext = "zip" if "windows" in target else "tar.gz"
        return f"portal-{tag}-{target}.{ext}"

    def windows(target: str) -> dict:
        name = archive(target)
        return {
            "url": f"{base}/{name}",
            "hash": sha256(folder, name),
            "extract_dir": f"portal-{tag}-{target}",
        }

    scoop = {
        "version": version,
        "description": DESCRIPTION,
        "homepage": f"https://github.com/{REPO}",
        "license": "MIT|Apache-2.0",
        "architecture": {
            "64bit": windows("x86_64-pc-windows-msvc"),
            "arm64": windows("aarch64-pc-windows-msvc"),
        },
        "bin": ["portal.exe", "portal-rendezvous.exe"],
        "checkver": "github",
        "autoupdate": {
            "architecture": {
                arch: {
                    "url": f"https://github.com/{REPO}/releases/download/v$version/portal-v$version-{target}.zip",
                    "hash": {"url": "$url.sha256"},
                    "extract_dir": f"portal-v$version-{target}",
                }
                for arch, target in [
                    ("64bit", "x86_64-pc-windows-msvc"),
                    ("arm64", "aarch64-pc-windows-msvc"),
                ]
            }
        },
    }
    bucket = ROOT / "bucket" / "portal.json"
    bucket.parent.mkdir(exist_ok=True)
    bucket.write_text(json.dumps(scoop, indent=4) + "\n", encoding="utf-8", newline="\n")

    def brew(target: str) -> str:
        name = archive(target)
        return f'      url "{base}/{name}"\n      sha256 "{sha256(folder, name)}"'

    formula = f'''# Generated by packaging/update_manifests.py for each release.
class Portal < Formula
  desc "{BREW_DESC}"
  homepage "https://github.com/{REPO}"
  version "{version}"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
{brew("aarch64-apple-darwin")}
    end
    on_intel do
{brew("x86_64-apple-darwin")}
    end
  end

  on_linux do
    on_arm do
{brew("aarch64-unknown-linux-gnu")}
    end
    on_intel do
{brew("x86_64-unknown-linux-gnu")}
    end
  end

  def install
    bin.install "portal", "portal-rendezvous"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/portal --version")
  end
end
'''
    tap = ROOT / "Formula" / "portal.rb"
    tap.parent.mkdir(exist_ok=True)
    tap.write_text(formula, encoding="utf-8", newline="\n")

    winget = ROOT / "packaging" / "winget"
    winget.mkdir(exist_ok=True)
    for old in winget.glob("*.yaml"):
        old.unlink()
    header = f"PackageIdentifier: {WINGET_ID}\nPackageVersion: {version}\n"
    footer = "ManifestVersion: 1.6.0\n"

    def installer(arch: str, target: str) -> str:
        name = archive(target)
        files = "".join(
            f"  - RelativeFilePath: portal-{tag}-{target}\\{exe}.exe\n"
            f"    PortableCommandAlias: {exe}\n"
            for exe in ["portal", "portal-rendezvous"]
        )
        return (
            f"- Architecture: {arch}\n"
            f"  InstallerUrl: {base}/{name}\n"
            f"  InstallerSha256: {sha256(folder, name).upper()}\n"
            f"  NestedInstallerFiles:\n{files}"
        )

    manifests = {
        f"{WINGET_ID}.yaml": header + "DefaultLocale: en-US\nManifestType: version\n" + footer,
        f"{WINGET_ID}.installer.yaml": header
        + "InstallerType: zip\nNestedInstallerType: portable\nCommands:\n- portal\nInstallers:\n"
        + installer("x64", "x86_64-pc-windows-msvc")
        + installer("arm64", "aarch64-pc-windows-msvc")
        + "ManifestType: installer\n"
        + footer,
        f"{WINGET_ID}.locale.en-US.yaml": header
        + "PackageLocale: en-US\n"
        + "Publisher: Marios Stefanidis\n"
        + "PublisherUrl: https://github.com/MStefa003\n"
        + "PackageName: Portal\n"
        + f"PackageUrl: https://github.com/{REPO}\n"
        + "License: MIT OR Apache-2.0\n"
        + f"LicenseUrl: https://github.com/{REPO}/blob/main/LICENSE-MIT\n"
        + f"ShortDescription: {json.dumps(DESCRIPTION)}\n"
        + "Tags:\n- file-transfer\n- p2p\n- encryption\n- cli\n"
        + f"ReleaseNotesUrl: https://github.com/{REPO}/releases/tag/{tag}\n"
        + "ManifestType: defaultLocale\n"
        + footer,
    }
    for name, text in manifests.items():
        (winget / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {bucket.relative_to(ROOT)}, {tap.relative_to(ROOT)} and {winget.relative_to(ROOT)} for {tag}")


if __name__ == "__main__":
    main()
